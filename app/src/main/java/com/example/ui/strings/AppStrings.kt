fun formatCurrency(amount: Double, currencyCode: String): String {
    val currency = CurrencyCode.fromCode(currencyCode)
    val nf = NumberFormat.getNumberInstance(Locale.US).apply {
        minimumFractionDigits = if (amount % 1.0 == 0.0) 0 else 2
        maximumFractionDigits = 2
    }
    val prefix = if (currency == CurrencyCode.BDT) "৳" else "SAR"
    return "$prefix ${nf.format(amount)}"
}

fun formatDateShort(millis: Long, language: AppLanguage): String {
    if (millis <= 0L) return ""
    val locale = if (language == AppLanguage.BN) Locale("bn", "BD") else Locale.ENGLISH
    return SimpleDateFormat("dd MMM yyyy", locale).format(Date(millis))
}

fun convertCurrency(
    amount: Double,
    fromCurrency: String,
    toCurrency: CurrencyCode,
    sarToBdtRate: Double
): Double {
    val from = CurrencyCode.fromCode(fromCurrency)
    if (from == toCurrency) return amount
    val rate = if (sarToBdtRate > 0.0) sarToBdtRate else 32.5
    return when {
        from == CurrencyCode.SAR && toCurrency == CurrencyCode.BDT -> amount * rate
        from == CurrencyCode.BDT && toCurrency == CurrencyCode.SAR -> amount / rate
        else -> amount
    }
}
